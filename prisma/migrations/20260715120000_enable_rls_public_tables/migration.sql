-- 배경: 이 프로젝트는 데이터 접근을 전적으로 Prisma(postgres role, 직결/풀러)로 하고,
-- Supabase 클라이언트는 Auth(auth 스키마)·Storage(storage 스키마)에만 쓴다. public 테이블을
-- PostgREST(.from/.rpc)로 읽는 코드는 0건이다. 그런데 RLS가 꺼져 있어 공개된 anon 키
