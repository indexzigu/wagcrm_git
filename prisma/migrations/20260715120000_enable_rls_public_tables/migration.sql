--
-- 조치: 모든 public 테이블에 RLS를 켠다. 정책(policy)을 하나도 만들지 않으면 anon·authenticated
-- 롤은 전부 거부된다 → Data API 노출이 닫힌다. Prisma가 쓰는 postgres 롤은 테이블 소유자이자
-- BYPASSRLS라 RLS의 영향을 받지 않고, service_role도 우회한다 → 앱 동작 무변화.
-- (FORCE 는 쓰지 않는다 — 소유자까지 RLS 대상이 되어 Prisma 경로를 깰 수 있다.)

