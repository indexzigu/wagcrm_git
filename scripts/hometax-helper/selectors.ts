export const EMPTY_SELECTOR_MAP: SelectorMap = { fields: {} };

/**
 * 셀렉터 맵을 읽는다. **없으면 빈 맵을 돌려준다** — 그 상태의 헬퍼는 필드를 하나도
 * 채우지 못하고 클릭도 못 하지만(허용 목록이 비어 있으므로), 그것이 안전한 기본값이다.
 * 파일이 없다는 이유로 추측 셀렉터를 쓰지 않는다.
 */
export async function loadSelectorMap(path: string = SELECTOR_MAP_PATH): Promise<SelectorMap> {
  let raw: string;
  try {
    raw = await readFile(path, "utf8");
  } catch {
    return EMPTY_SELECTOR_MAP;
  }
  const parsed = JSON.parse(raw) as SelectorMap;
  if (!parsed || typeof parsed !== "object" || typeof parsed.fields !== "object") {
    throw new Error(`셀렉터 맵 형식이 올바르지 않습니다: ${path}`);
  }
  return { ...EMPTY_SELECTOR_MAP, ...parsed };
}

export function allowedClickLabels(map: SelectorMap): string[] {
  return Object.keys(map.navigation ?? {});
}
