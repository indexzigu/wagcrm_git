/**
 * 정산 두 표(「정산 진행 중」·「정산 완료」)가 공유하는 **가로 폭 규약**.
 *
 * ## 왜 한 파일인가
 * 두 표는 같은 페이지에 세로로 붙어 있어 체크박스 폭·캠페인명 시작 좌표·오른쪽 끝이
 * 어긋나면 즉시 보인다(2026-08-25 오너 신고 결함이 정확히 그것이었다). 종전에는 같은
 * 규약이 두 파일에 손으로 복제돼 한쪽만 고치면 갈렸다 — 이 모듈이 그 짝을 고정한다.
 *
 * ## 규약
 * 1. **체크박스 열은 어떤 폭에서도 정확히 48px.** 비율로 두면 넓은 화면에서 부풀어
 *    두 표의 캠페인명 시작 좌표가 어긋난다(1600px 실측 48→63.59px).
 * 2. **캠페인명은 폭 미지정 흡수 열.** CSS 표 사양상 폭이 지정되지 않은 열이 하나라도
 *    있으면 남는 폭은 그 열로만 가고 나머지 열은 선언폭을 정확히 유지한다 — 이것이
 *    1번을 지켜 주는 장치다. ⛔ 캠페인명에 폭을 주지 말 것.
 * 3. **나머지 열은 `fluidCol(px)` 로 유동폭.** 최소폭에서의 자기 픽셀을 **표 폭에 대한
 *    백분율**로 환산해 들고 있으므로, 창이 넓어지면 열이 함께 넓어지고 그만큼 필드
 *    사이 여백이 벌어진다. 남는 몫은 흡수 열(캠페인명)이 가져간다.
 * 4. **`MIN_WIDTH` 아래에서는 오늘과 완전히 같은 레이아웃.** 인자로 넘기는 `px` 값이
 *    곧 최소폭에서의 실제 픽셀이라(예산이 그 합으로 잡혀 있다) 좁은 화면 동작은 불변이고,
 *    넘치면 종전대로 가로 스크롤이 된다.
 *
 * ## 왜 유동폭으로 바꿨나 (오너 요청 2026-08-28)
 * 종전에는 표에 `max-w-[1060px]` 상한이 있었다. 그 상한은 「흡수 열 하나에 죽은 여백이
 * 쌓이는 문제」를 막으려던 것인데(1600px 에서 캠페인명 533px 배정 / 171px 필요), 대가로
 * 넓은 화면에서 **카드 오른쪽에 빈 띠**가 생겼다 — 죽은 여백을 한 열 안에서 표 밖으로
 * 옮겼을 뿐 총량은 같았다. 유동폭은 그 여백을 **모든 열에 비율로 흩는다.**
 *
 * ⚠️ **남는 폭은 반드시 어딘가로 간다 — 선택지는 셋뿐이고 앞의 둘은 이미 반려됐다.**
 * ①한 열(캠페인명)에 몰기 = 2026-08-26 오너 지적 ②표 밖 빈 띠로 두기 = 2026-08-28 오너
 * 지적 ③전 열에 비율로 흩기 = 지금. 셋 중 ③이 여백을 가장 얇게 편다.
 * ⛔ 그러므로 **1060 같은 「컨테이너보다 작은 상한」을 되살리지 말 것** — ②로 되돌아간다.
 * (금지되는 것은 그 실패한 조건이지 상한이라는 개념 자체가 아니다. 오너가 「아주 넓은
 * 화면에서는 이쯤에서 멈춰라」를 새로 정한다면, 그때는 실측한 새 상한을 오너 결정으로
 * 세우고 이 문단을 함께 고친다.)
 *
 * 🔎 **알려진 대가(ss-ux-designer 검토 2026-08-28):** 표가 넓어질수록 금액 열 사이도 함께
 * 벌어져 같은 행의 숫자를 훑는 눈의 이동 거리가 는다. 고밀도 운영 표면에서는 바람직하지
 * 않지만, 금액 열만 고정폭으로 되돌리면 남는 폭이 전부 캠페인명으로 몰려 ①로 돌아간다
 * (검토안이 함께 제안한 「캠페인명 상한」까지 걸면 셋을 동시에 만족시킬 수 없어 ②가 된다).
 * 즉 이건 고칠 수 있는 결함이 아니라 ③을 고른 대가다.
 */

/**
 * 표의 최소 폭. 이 값이 곧 **폭 예산의 분모 기준**이다 — `fluidCol(px)` 의 `px` 는
 * "표가 이 폭일 때의 실제 픽셀"을 뜻한다.
 * 1280px 뷰포트에서 카드 안쪽 폭이 1126px 이므로 994 는 그 아래 — 즉 기본 화면에서는
 * 가로 스크롤이 생기지 않는다(2026-08-28 실측. 사이드바가 호버 오버레이로 바뀌어(#528)
 * 레이아웃 폭을 먹지 않으므로, 종전 기록의 997px 보다 여유가 늘었다).
 * ⚠️ 이 값을 올리면 좁은 화면에서 스크롤이 되살아난다.
 */
export const SETTLEMENT_TABLE_MIN_WIDTH = 994;

/** 체크박스(선택) 열 — 규약 1. 두 표가 반드시 같은 값을 쓴다. */
export const SETTLEMENT_TABLE_CHECKBOX_WIDTH = 48;

/** `<table>` 에 얹는 인라인 스타일 — `w-full` 과 짝이다(⛔ `max-w` 를 함께 주지 말 것). */
export const settlementTableStyle = {
  minWidth: `${SETTLEMENT_TABLE_MIN_WIDTH}px`,
} as const;

/** 체크박스 열 `<col>` 스타일 — 어떤 폭에서도 고정 48px(규약 1). */
export const settlementCheckboxCol = {
  width: `${SETTLEMENT_TABLE_CHECKBOX_WIDTH}px`,
} as const;

/**
 * 유동폭 `<col>` 스타일. `basePx` = 표가 최소폭(994px)일 때의 실측 필요폭이고,
 * 그 폭에 대한 **백분율**로 환산한다 — 표가 넓어지면 같은 비율로 함께 넓어진다.
 *
 * 🪤 **`calc()` 로 `%` 와 `px` 를 섞지 말 것 — 표 열에서는 무시된다.**
 * `width: calc((100% - 48px) * 86 / 946)` 은 CSS 로는 정상 파싱되지만
 * (`getAttribute("style")` 에 `calc(9.09091% - 4.36364px)` 로 남는다)
 * `table-layout: fixed` 의 열 폭으로는 **적용되지 않아** 그 열이 폭 미지정으로
 * 떨어진다 — 실측에서 9개 열이 전부 119.55px 로 균등 분배됐다(Chrome, 2026-08-28).
 * 순수 백분율(`9%`)과 백분율만 든 `calc(9% * 1)` 은 정상 동작한다.
 * 그래서 체크박스 48px 를 식에서 빼지 않고 **분모를 최소폭 전체(994)로** 잡는다.
 */
export function settlementFluidCol(basePx: number) {
  return {
    width: `${((basePx / SETTLEMENT_TABLE_MIN_WIDTH) * 100).toFixed(4)}%`,
  } as const;
}
