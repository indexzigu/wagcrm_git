/**
 * 손익(흑자/적자) 색 규칙 SSOT — 흰 카드 표면 전용.
 *
 * **맵이 둘이다.** 판정(`resolveProfitTone`)은 하나지만 강도는 표면 밀도로 갈린다 —
 * 초점 값은 `PROFIT_TONE_TEXT`, 표·원장은 `PROFIT_TONE_TEXT_DENSE`(적자만 색).
 * 고르는 기준은 `ProfitToneDensity` 주석에 있다. 새 소비처는 **반드시 둘 중 하나를
 * 명시적으로 고른다** — 기본값을 두면 밀집 표면이 조용히 초점 강도를 받는다.
 *
 * `goal-band.ts`(히어로 달성 밴드)와 같은 이유로 한 곳에 둔다: 화면마다 삼항을 새로 쓰면
 * 규칙이 갈라진다. 실제로 갈라져 있었다 —
 * - `settlement-table.tsx` 영업이익 열: **부호 무관 무조건 `emerald-600`**(적자도 초록).
 * - `settlement-page-client.tsx` 최종 영업 이익: **부호 무관 무조건 `text-primary`**(적자도 네이비).
 * - `pnl-report-client.tsx` 월별 표 순이익·이익률: 음수여도 무색.
 * 셋 다 같은 파생값(손익)인데 표면마다 다른(그리고 전부 부호를 무시하는) 규칙을 썼다.
 *
 * **적자에 `--money-out` 을 쓰지 않는다.** 그 토큰은 정의 주석이 *"지급은 위험이 아니라서
 * --status-urgent 에 흡수할 수 없다"* 고 선언한 **반대편 축**이다. 기준은 단위(₩ vs %)가 아니라
 * **"실제 이체냐 계산된 판정이냐"** 다 — 셀러 지급액은 돈이 실제로 나가는 사건이라 money-out 이지만,
 * 손익이 마이너스인 건 위 줄들이 상쇄된 **결과값**이지 추가 이체가 아니다. 여기서 money-out 을
 * 재사용하면 캘린더 링처럼 그 토큰을 차분하게 쓰는 자리들의 의미까지 흔들린다.
 * (ss-ux-designer 판정 2026-07-15, 모바일 트랙의 같은 판정과 동일 근거)
 *
 * 대비(흰 배경): `--money-in-text` #047857 = 5.48:1 · `--status-urgent-text` #8F3C3C = 7.29:1.
 * 둘 다 AA 통과. 기본 `--status-urgent`(#BF5050)는 4.69:1 로 경계라, 소형 텍스트가 섞이는
 * 표·원장에서는 `-text` 변형을 쓴다(`mobile-outreach-view.tsx` 선례와 같은 근거).
 *
 * **네이비 표면에 쓰지 말 것** — 히어로처럼 어두운 배경의 손익/달성 표현은 `goal-band.ts` 소관이다.
 */

export type ProfitTone = "profit" | "loss";

/**
 * 손익 금액·비율 → 톤. 값이 없으면 `null`(호출부가 무채색을 유지).
 *
 * 경계: `0`은 **흑자(profit)** 다 — 손실이 아니므로 경고를 띄우지 않는다.
 */
export function resolveProfitTone(value: number | null | undefined): ProfitTone | null {
  if (value == null || !Number.isFinite(value)) return null;
  return value < 0 ? "loss" : "profit";
}

/**
 * 표면 밀도 — **같은 판정이라도 몇 개가 동시에 보이는가**로 강도가 갈린다.
 *
 * P8 「색 사용 원칙 §3 맥락별 강도」의 코드화다: *초점 숫자(히어로·타일) = 완전히 /
 * 목록 행·원장 = 저강도 / 표 = 주의가 필요한 소수만.* 종전엔 이 축이 코드에 아예
 * 없어서 모든 소비처가 초점 강도를 받았고, 그 결과가 아래 `PROFIT_TONE_TEXT_DENSE`
 * 주석이 설명하는 "전 행 초록"이다.
 *
 * - `focal` — 화면(또는 패널)당 1~2개뿐인 결론 값. KPI 타일·상세 패널 헤더·선택 요약 바.
 * - `dense` — 행마다 되풀이되는 값. 표 열·원장 줄.
 *
 * 판단 기준은 "중요한가"가 아니라 **"몇 개가 동시에 뜨는가"** 다. 그림자 사다리와 같은
 * 논리다(P8 Elevation Ladder) — 다 띄우면 아무것도 안 뜬다.
 */
export type ProfitToneDensity = "focal" | "dense";

/**
 * 톤별 텍스트 색 — 흰 카드 위 손익 값 전용. **초점(`focal`) 강도.**
 *
 * 흑자에 초록을 주는 건 "성공"이라서가 아니라 **우리에게 남은 돈**이라는 자금 방향이다
 * (`--status-success` 와 값이 같아도 토큰이 분리된 이유 — globals.css 참조).
 *
 * ⚠️ **밀집 표면에 이 맵을 쓰지 말 것** — 아래 `PROFIT_TONE_TEXT_DENSE` 를 쓴다.
 */
export const PROFIT_TONE_TEXT: Record<ProfitTone, string> = {
  profit: "text-money-in-text",
  loss: "text-status-urgent-text",
};

/**
 * 톤별 텍스트 색 — **밀집(`dense`) 강도. 적자에만 색이 있다.**
 *
 * `profit` 키가 비어 있는 것이 누락이 아니라 **선언**이다: 밀집 표면의 흑자는 색을 받지
 * 않고 본문 색을 상속한다.
 *
 * 왜 갈랐나 (오너 지적 2026-08-26). 손익 표는 대부분의 행이 흑자라 초점 강도를 그대로
 * 쓰면 **열 전체가 초록**이 된다. 그러면 색이 값의 함수이기를 멈추고 그냥 그 열의
 * 배경이 된다 — 같은 날 걷어낸 "전 행에 뜨는 비용 미입력 배지"와 **구조가 같은 습관화**다.
 * P8 §2 가 이미 이것을 이름으로 지목해 뒀다: *"흑자를 초록으로 칠하면 적자가 안 보이고,
 * 원장 5줄을 다 빨갛게 칠하면 매달 뜨는 빨강이라 습관화로 신호를 잃는다."*
 *
 * ⚠️ **"흑자도 색이 있어야 대칭"이라며 `profit` 키를 채우지 말 것.** 대칭은 목표가
 * 아니다 — 이 축이 존재하는 이유는 **적자를 눈에 띄게 하는 것**이고, 흑자를 칠하는 순간
 * 적자가 묻힌다. 반대로 초점 타일에서 초록을 걷는 것도 회귀다(거기선 값이 1~2개뿐이라
 * 색이 여전히 값의 함수다 — P8 §3 「초점 숫자 = 완전히」).
 *
 * 적자 색은 초점과 **같은 토큰**을 쓴다. 밀도는 "흑자를 칠하는가"만 가르고 적자의 세기는
 * 건드리지 않는다 — 표면이 같으면(흰 카드) 대비 계산도 같기 때문이다(P8 §5).
 */
export const PROFIT_TONE_TEXT_DENSE: Partial<Record<ProfitTone, string>> = {
  loss: "text-status-urgent-text",
};
