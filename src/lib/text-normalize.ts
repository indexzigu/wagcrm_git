/**
 * 외부에서 들어온 한국어 문자열을 **비교하기 전에** 통과시키는 정규화 SSOT.
 *
 * ## 왜 별도 모듈인가
 *
 * 원래 `mail-config.ts`(메일 서버 좌표 SSOT)가 `toNfc` 를 함께 들고 있었는데, 소비처가
 * 메일 밖(회신 엑셀 파서)까지 늘면서 **한 모듈이 서로 다른 두 이유로 바뀌게** 됐다.
 * 정규화는 메일에 종속된 개념이 아니므로 여기로 뺀다(교차 검증 지적 2026-09-02).
 *
 * ## 무엇을 막는가 — 자모 분리(NFD)
 *
 * 같은 한글이 **조합형(NFC)**과 **자모 분리형(NFD)** 두 벌로 존재한다. 눈에는 똑같은데
 * 문자열로는 다르다 — 실측: `세금계산서` 가 NFC 5코드포인트 / NFD 12코드포인트.
 * 그래서 `===` 도 `includes` 도 전부 빗나가고, 결과는 언제나 **조용한 0건**이다:
 *
 * - 구글이 돌려주는 편지함·라벨 이름 → `pickTaxInvoiceBox` 가 INBOX 로 폴백해 스캔 0건인데
 *   화면에는 「메일 미발견」으로 보여 실제 미수취와 구분되지 않는다.
 * - 메일 제목·첨부 파일명·회신 엑셀의 헤더와 셀 값 → 「송장번호를 찾지 못했습니다」.
 *
 * ⚠️ **형태를 정하는 주체가 둘이라 실측으로 미리 못 거른다.** 편지함 이름은 메일 사업자가,
 * 제목·파일명·엑셀 내용은 **보낸 사람**이 정한다(맥에서 만든 파일은 NFD 가 상시 조건이다).
 * 그래서 「우리 상수와 맞대는 외부 문자열」은 예외 없이 여기를 거친다.
 *
 * ⛔ 지우지 말 것. 다음메일 시절에는 드러나지 않다가 구글 전환에서 터진 종류다.
 */

/** 자모 분리형을 조합형으로 맞춘다. 우리 소스 리터럴은 NFC 로 커밋되므로 한쪽만 걸면 된다. */
export function toNfc(value: string): string {
  return value.normalize("NFC");
}

/**
 * **느슨한 비교**용 정규화 — NFC + 공백 제거 + 소문자화.
 *
 * 편지함 이름·메일 제목·첨부 파일명이 공통으로 쓰던 세 단계가 각자 손으로 적혀 있었다.
 * 한 벌만 고치면 나머지가 조용히 갈리는 형태라(이 트랙이 고친 「호스트가 각자 리터럴로
 * 박혀 있었다」와 같은 모양) 여기로 모은다.
 *
 * ⚠️ **정확 일치가 필요한 자리에는 쓰지 말 것** — 대소문자·공백까지 뭉개므로
 * `세금계산서` 와 `세금 계산서 보관` 을 가르지 못한다. 그런 자리는 `toNfc` 만 쓴다.
 */
export function normalizeForCompare(value: string): string {
  return toNfc(value).replace(/\s+/g, "").toLowerCase();
}
